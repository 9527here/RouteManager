#!/usr/bin/env python3
"""Emit config/joint_names.yaml from the built URDF + drive gains.

Keeping this generated means the group lists and limits can never drift out of
sync with urdf/humanoid_upper_body_v3.urdf.
"""
import json
import math
import xml.etree.ElementTree as ET
from pathlib import Path

from naming_rules import joint_source_key

HERE = Path(__file__).resolve().parent
PKG = HERE.parent

robot = ET.parse(PKG / "urdf" / "humanoid_upper_body_v3.urdf").getroot()
gains = json.loads((HERE / "drive_gains.json").read_text())

# Joint names are the rule-compliant ones (scripts/naming_rules.py).
GROUPS = {
    "lift":        ["lift_joint"],
    "torso":       ["torso_pitch_joint"],
    "head":        ["head_yaw_joint", "head_pitch_joint"],
    "left_arm":    [f"left_arm_{k}_joint" for k in range(1, 7)]
                   + ["left_wrist_joint"],
    "right_arm":   [f"right_arm_{k}_joint" for k in range(1, 7)]
                   + ["right_wrist_joint"],
    "castor_swivel": ["caster_front_left_joint", "caster_rear_left_joint",
                      "caster_front_right_joint", "caster_rear_right_joint"],
    "wheels":      ["front_left_wheel_joint", "rear_left_wheel_joint",
                    "front_right_wheel_joint", "rear_right_wheel_joint"],
}
ARM_ROLES = {
    1: "shoulder roll", 2: "shoulder pitch", 3: "upper-arm roll",
    4: "ELBOW pitch [SIGN UNVERIFIED - symmetric range]",
    5: "forearm roll", 6: "wrist pitch",
}
ROLES = {
    "lift_joint": "vertical lift column (prismatic)",
    "torso_pitch_joint": "torso lean, pitch about +Y",
    "head_yaw_joint": "head yaw",
    "head_pitch_joint": "head pitch [SIGN UNVERIFIED - symmetric range]",
    "left_wrist_joint": "left wrist roll",
    "right_wrist_joint": "right wrist roll",
    "caster_front_left_joint": "castor swivel, front left (held at 0 - no CAD swivel clearance)",
    "caster_rear_left_joint": "castor swivel, rear left (held at 0 - no CAD swivel clearance)",
    "caster_front_right_joint": "castor swivel, front right (held at 0 - no CAD swivel clearance)",
    "caster_rear_right_joint": "castor swivel, rear right (held at 0 - no CAD swivel clearance)",
    "front_left_wheel_joint": "castor wheel, front left (continuous)",
    "rear_left_wheel_joint": "castor wheel, rear left (continuous)",
    "front_right_wheel_joint": "castor wheel, front right (continuous)",
    "rear_right_wheel_joint": "castor wheel, rear right (continuous)",
}
for side in ("left", "right"):
    for n, r in ARM_ROLES.items():
        ROLES[f"{side}_arm_{n}_joint"] = f"{side} {r}"


def role(name):
    return ROLES.get(name, "unknown")


out = [
    "# Joint groups, limits and drive gains for humanoid_upper_body_v3.",
    "# GENERATED by scripts/gen_joint_config.py - do not hand-edit.",
    "# Angles in rad (range_deg is informational); prismatic in m.",
    "# See README.md for the provenance of every limit and gain.",
    "",
    "groups:",
]
for g, members in GROUPS.items():
    out.append(f"  {g}: [{', '.join(members)}]")
out += ["", "joints:"]

for j in robot.findall("joint"):
    name, jtype = j.get("name"), j.get("type")
    if jtype == "fixed":
        continue
    lt = j.find("limit")
    dy = j.find("dynamics")
    gk = next((g for g, m in GROUPS.items() if name in m), "other")
    gain = gains.get(joint_source_key(name), {})

    out.append(f"  {name}:")
    out.append(f"    role: {role(name)}")
    out.append(f"    type: {jtype}")
    out.append(f"    group: {gk}")
    if lt.get("lower") is not None:
        lo, hi = float(lt.get("lower")), float(lt.get("upper"))
        out.append(f"    lower: {lo:.6f}")
        out.append(f"    upper: {hi:.6f}")
        if jtype == "revolute":
            out.append(f"    range_deg: [{math.degrees(lo):.1f}, {math.degrees(hi):.1f}]")
    else:
        out.append("    lower: null      # continuous - unlimited rotation")
        out.append("    upper: null")
    out.append(f"    effort: {float(lt.get('effort')):g}")
    out.append(f"    velocity: {float(lt.get('velocity')):g}")
    out.append(f"    urdf_damping: {float(dy.get('damping')):g}")
    out.append(f"    drive_target: {gain.get('target', 'position')}")
    out.append(f"    drive_stiffness: {gain.get('stiffness')}")
    out.append(f"    drive_damping: {gain.get('damping')}")

dst = PKG / "config" / "joint_names.yaml"
dst.parent.mkdir(parents=True, exist_ok=True)
dst.write_text("\n".join(out) + "\n")
print(f"-> {dst}  ({len(out)} lines)")
